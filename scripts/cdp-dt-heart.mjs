import fs from 'node:fs';
const PORT = process.env.PORT || '5174';
const CDP = process.env.CDP || '9226';
const TOKEN = fs.readFileSync(process.env.TOKEN_FILE, 'utf8').trim();
const targets = await (await fetch(`http://localhost:${CDP}/json`)).json();
const page = targets.find((t) => t.type === 'page') || targets[0];
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
const send = (m, p = {}) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method: m, params: p })); });
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } });
await new Promise((r) => ws.addEventListener('open', r));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const ev = async (x) => (await send('Runtime.evaluate', { expression: x, returnByValue: true })).result.value;
await send('Page.enable'); await send('Runtime.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 1280, height: 900, deviceScaleFactor: 1, mobile: false });
await send('Page.navigate', { url: `http://localhost:${PORT}/` }); await wait(1500);
await ev(`localStorage.setItem('bt_token', ${JSON.stringify(TOKEN)})`);
await send('Page.navigate', { url: `http://localhost:${PORT}/product` }); await wait(3000);
const before = await ev(`(()=>{const b=[...document.querySelectorAll('button[aria-label]')].find(x=>/wishlist/i.test(x.getAttribute('aria-label')||''));return b?b.getAttribute('aria-label'):'none';})()`);
await ev(`[...document.querySelectorAll('button[aria-label]')].find(x=>/wishlist/i.test(x.getAttribute('aria-label')||'')).click()`);
await wait(1300);
const after = await ev(`(()=>{const b=[...document.querySelectorAll('button[aria-label]')].find(x=>/wishlist/i.test(x.getAttribute('aria-label')||''));return b?b.getAttribute('aria-label'):'none';})()`);
console.log('dt heart before:', before, '| after:', after);
ws.close();
